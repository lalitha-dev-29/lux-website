#!/usr/bin/env node
// One-off generator: parses every `<path class="country" data-name="…">` out
// of src/data/world-map-paths.svg and writes two committed, static lookup
// files consumed at runtime:
//   - src/data/mapCentroids.ts — a marker (x,y) position for every country,
//     in the SVG's own 0..960 / 0..500 viewBox coordinate space, so the
//     public Atlas page never asks an admin to enter coordinates.
//   - src/lib/mapIds.ts — the sorted list of every valid "Map Identifier"
//     value, used to populate the admin's Map Identifier <select> so it can
//     never drift out of sync with the actual map artwork.
//
// A country's `d` attribute can contain more than one sub-path (island
// exclaves, e.g. Canada's arctic islands or France's Corsica) — each
// sub-path starts with its own "M" command (this SVG only ever uses
// M/L/Z). We pick the sub-path with the largest bounding-box area as the
// "mainland" region so a marker never lands in open ocean between a
// mainland and a small far-flung territory.
//
// Not imported by the app at runtime — this is dev-time tooling, run once
// (and re-run only if world-map-paths.svg is ever redrawn):
//   node scripts/generate-atlas-centroids.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const svgPath = path.join(root, 'src/data/world-map-paths.svg');
const centroidsOutPath = path.join(root, 'src/data/mapCentroids.ts');
const mapIdsOutPath = path.join(root, 'src/lib/mapIds.ts');

const svg = readFileSync(svgPath, 'utf-8');

const pathRe = /<path class="country" data-name="([^"]*)" data-slug="([^"]*)" d="([^"]*)"/g;

/** @returns {{minX:number,maxX:number,minY:number,maxY:number,area:number,cx:number,cy:number}} */
function bboxOf(points) {
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  for (const [x, y] of points) {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
  return { minX, maxX, minY, maxY, area: (maxX - minX) * (maxY - minY), cx: (minX + maxX) / 2, cy: (minY + maxY) / 2 };
}

const pairRe = /(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)/g;

function largestSubpathCentroid(d) {
  // Every sub-path in this file starts with its own "M" (only M/L/Z are
  // ever used), so splitting on "M" isolates each one.
  const subpaths = d.split('M').filter(Boolean);
  let best = null;
  for (const sub of subpaths) {
    const points = [];
    for (const m of sub.matchAll(pairRe)) points.push([parseFloat(m[1]), parseFloat(m[2])]);
    if (points.length === 0) continue;
    const box = bboxOf(points);
    if (!best || box.area > best.area) best = box;
  }
  if (!best) throw new Error('Path with no parseable coordinates');
  return { x: Math.round(best.cx * 100) / 100, y: Math.round(best.cy * 100) / 100 };
}

const centroids = {};
const mapIds = [];

for (const match of svg.matchAll(pathRe)) {
  const [, name, , d] = match;
  centroids[name] = largestSubpathCentroid(d);
  mapIds.push(name);
}

mapIds.sort((a, b) => a.localeCompare(b));

const centroidsBody = Object.entries(centroids)
  .map(([name, { x, y }]) => `  ${JSON.stringify(name)}: { x: ${x}, y: ${y} },`)
  .join('\n');

writeFileSync(
  centroidsOutPath,
  `// AUTO-GENERATED by scripts/generate-atlas-centroids.mjs — do not hand-edit.
// Regenerate after any change to src/data/world-map-paths.svg.
//
// Marker (x,y) position for every country in the world map, in the SVG's
// own 0..960 / 0..500 viewBox coordinate space. Keyed by the exact SVG
// \`data-name\` value (== an atlas_countries.map_id value once a country is
// published). Looked up automatically by AtlasMap.astro — admins never
// enter coordinates.

export const mapCentroids: Record<string, { x: number; y: number }> = {
${centroidsBody}
};
`
);

const mapIdsBody = mapIds.map((name) => `  ${JSON.stringify(name)},`).join('\n');

writeFileSync(
  mapIdsOutPath,
  `// AUTO-GENERATED by scripts/generate-atlas-centroids.mjs — do not hand-edit.
// Regenerate after any change to src/data/world-map-paths.svg.
//
// Every valid "Map Identifier" value — the exact set of \`data-name\` values
// on the country paths in src/data/world-map-paths.svg. The admin's Map
// Identifier field is a <select> constrained to this list so it can never
// drift out of sync with the map artwork.

export const MAP_IDS: string[] = [
${mapIdsBody}
];
`
);

console.log(`Wrote ${mapIds.length} entries to:\n  ${path.relative(root, centroidsOutPath)}\n  ${path.relative(root, mapIdsOutPath)}`);

// Spot-check against today's hand-placed centroids (src/data/atlas.ts) so an
// obviously-wrong "largest sub-path" pick gets caught before being trusted.
const knownGood = {
  France: { x: 485.65, y: 100.47 },
  'United Kingdom': { x: 473.5, y: 78.51 },
  Italy: { x: 509.96, y: 112.4 },
  India: { x: 689.2, y: 174.55 },
  Japan: { x: 826.66, y: 128.36 },
};
console.log('\nSpot-check vs. hand-placed values in src/data/atlas.ts:');
for (const [name, expected] of Object.entries(knownGood)) {
  const got = centroids[name];
  const dx = got ? Math.abs(got.x - expected.x) : NaN;
  const dy = got ? Math.abs(got.y - expected.y) : NaN;
  const flag = !got || dx > 15 || dy > 15 ? '  <-- CHECK THIS' : '';
  console.log(`  ${name.padEnd(16)} expected (${expected.x}, ${expected.y})  got (${got?.x}, ${got?.y})${flag}`);
}
